export const postSlugs = posts.map((p) => p.slug);

export function getPost(slug: string): Post | undefined {
  return posts.find((p) => p.slug === slug);
}

export function stripHtml(s: string): string {
  return s.replace(/<[^>]+>/g, "");
}

export function postText(p: Post): string {
  return p.body
    .map((b) => {
      switch (b.t) {
        case "h2":
        case "h3":
          return b.text;
        case "p":
        case "note":
          return stripHtml(b.html);
        case "ul":
        case "ol":
          return b.items.map(stripHtml).join(" ");
        case "table":
          return [...b.head, ...b.rows.flat()].join(" ");
      }
    })
    .join(" ");
}

export function readingMinutes(p: Post): number {
  const words = postText(p).split(/\s+/).length;
  return Math.max(2, Math.round(words / 190));
}

